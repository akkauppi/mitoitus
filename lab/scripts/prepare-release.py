"""Build and stage only the reviewed public allowlist for GitHub Pages."""
import json
import shutil
from pathlib import Path
from candidate import ROOT, OFFLINE, PUBLIC_FILES, build, digest, verify_candidate


def prepare():
    candidate = ROOT / 'lab/book'
    report = build(replace=candidate.exists())
    if not report.get('publicationReady') or report.get('legacyFallbackReplacementPending'):
        raise ValueError('Candidate has not passed the release artifact gate')
    verify_candidate(candidate)
    target = ROOT / 'lab/.build/release'
    if target.exists():
        # The output path is fixed and only this script owns it.
        if target.is_symlink() or not (target / '.release-output').is_file():
            raise ValueError('Refusing to replace an unowned release directory')
        shutil.rmtree(target)
    target.mkdir(parents=True)
    (target / '.release-output').write_text('Generated by lab/scripts/prepare-release.py\n')
    for name in (*PUBLIC_FILES, OFFLINE):
        path = target / name
        path.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(candidate / name, path)
    (target / '.nojekyll').touch()
    manifest = {'edition': '2026-11-13', 'panels': report['panels'], 'sheets': report['sheets'],
                'files': {name: digest((target/name).read_bytes()) for name in (*PUBLIC_FILES, OFFLINE)}}
    (target / 'release.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(f'Release staged: {target} ({len(PUBLIC_FILES)+1} public assets)')
    return target


if __name__ == '__main__':
    prepare()
